// Generates docs/DDJ-SB-TEST-MATRIX.md from the built-in mapping so the
// hardware test matrix can never drift from what the app actually does.
import { build } from "esbuild";
import { mkdirSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import path from "node:path";

const outDir = path.resolve("node_modules/.cache/dbdj");
mkdirSync(outDir, { recursive: true });
const outfile = path.join(outDir, "matrix-entry.mjs");
await build({
  stdin: {
    contents: `export { buildDdjSbMapping } from "./src/controllers/profiles/pioneer-ddj-sb.ts";
               export { actionCatalog } from "./src/core/actions.ts";
               export { describeSelector } from "./src/controllers/mapping/schema.ts";`,
    resolveDir: process.cwd(),
    loader: "ts",
  },
  bundle: true,
  format: "esm",
  platform: "node",
  outfile,
  logLevel: "silent",
});
const { buildDdjSbMapping, actionCatalog, describeSelector } = await import(pathToFileURL(outfile).href + `?t=${Date.now()}`);

const m = buildDdjSbMapping();
const catalog = actionCatalog();
const h = (n) => "0x" + n.toString(16).toUpperCase().padStart(2, "0");
const RESPONSE = {
  "deck1.play": "Deck A toggles play/pause", "deck2.play": "Deck B toggles play/pause",
  "deck1.cue": "CDJ cue: set / return / preview while held", "deck2.cue": "CDJ cue: set / return / preview while held",
  "deck1.tempo": "Deck A tempo % changes (display)", "deck2.tempo": "Deck B tempo % changes (display)",
  "deck1.jog.platter": "Scratch when touched in VINYL mode, else nudge/seek", "deck2.jog.platter": "Scratch when touched in VINYL mode, else nudge/seek",
  "deck1.jog.ring": "Nudge while playing, fine seek while paused", "deck2.jog.ring": "Nudge while playing, fine seek while paused",
  "deck1.jog.touch": "TOUCH/SCRATCH chip lights", "deck2.jog.touch": "TOUCH/SCRATCH chip lights",
  "mixer.crossfader": "Crossfader moves; A/B levels change",
  "browser.scroll": "Library selection moves",
  "browser.load.deck1": "Selected track loads into Deck A", "browser.load.deck2": "Selected track loads into Deck B",
};

const rows = [];
for (const c of m.controls) {
  const inputs = m.inputs.filter((b) => b.control === c.id);
  const leds = m.outputs.filter((o) => o.control === c.id);
  inputs.forEach((b, i) => {
    const meta = catalog.get(b.action);
    const impl = b.action === "modifier.shift" || meta?.implemented !== false;
    const layer = b.modifier ? `${b.modifier.toUpperCase()} layer` : b.note ?? "";
    rows.push(
      `| ${i === 0 ? `**${c.label}**` : ""} | ${describeSelector(b.midi)} ${layer ? `<br><sub>${layer}</sub>` : ""} | \`${b.action}\` | ${impl ? RESPONSE[b.action] ?? meta?.label ?? "" : "_not implemented yet (logged once)_"} | ${i === 0 && leds.length ? leds.map((o) => `${h(o.midi.number)}→${o.feedback}`).join("<br>") : ""} | ☐ |`,
    );
  });
}

const md = `# Pioneer DDJ-SB — Hardware Test Matrix

> Generated by \`npm run docs:test-matrix\` from \`src/controllers/profiles/pioneer-ddj-sb.ts\`. Do not edit by hand.

How to use: follow **docs/HARDWARE-TEST-PLAN.md**. The in-app **Controller test** tab tracks the same controls live
and exports a filled-in report ("Copy test report"), which is the easiest way to report a failing control.

MIDI channels are 1-based (status 0x90 = channel 1). "CC14" = 14-bit value sent as MSB then LSB (LSB = MSB + 0x20).

| Control | Expected MIDI input | Mapped command | Application response | LED / output | Pass/Fail |
|---|---|---|---|---|---|
${rows.join("\n")}

Totals: ${m.controls.length} physical controls, ${m.inputs.length} input bindings, ${m.outputs.length} LED outputs.
`;
writeFileSync("docs/DDJ-SB-TEST-MATRIX.md", md);
console.log(`Wrote docs/DDJ-SB-TEST-MATRIX.md (${m.controls.length} controls, ${m.inputs.length} bindings)`);
